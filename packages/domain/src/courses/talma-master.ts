/**
 * Transcribed from Golf Talma's June 2017 Master slope-table images. Each tuple is
 * [minimum Handicap Index, maximum Handicap Index, published playing handicap].
 * This is intentionally static lookup data: no WHS calculation is performed at runtime.
 */
function publishedRanges(
  rows: readonly (readonly [minimum: number, maximum: number, playingHandicap: number])[],
): readonly HandicapIndexRange[] {
  return rows.map(([minimum, maximum, playingHandicap]) => ({
    minimum,
    maximum,
    playingHandicap,
  }));
}

