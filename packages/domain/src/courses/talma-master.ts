export const teeLabels = ['48', '52', '56', '60', '64'] as const;

export type TeeLabel = (typeof teeLabels)[number];
export type RatingTable = 'men' | 'women';

export type HandicapIndexRange = {
  minimum: number;
  maximum: number;
  playingHandicap: number;
};

export type PlayingHandicapLookupTable = Readonly<
  Record<TeeLabel, Readonly<Record<RatingTable, readonly HandicapIndexRange[]>>>
>;

export class PlayingHandicapLookupError extends Error {
  public constructor(
    public readonly teeLabel: string,
    public readonly ratingTable: string,
    public readonly handicapIndex: number,
  ) {
    super(
      `Tasoitusindeksille ${handicapIndex} ei löydy Golf Talma Masterin tiin ${teeLabel} ${ratingTable === 'men' ? 'miesten' : ratingTable === 'women' ? 'naisten' : 'valitusta'} virallisesta pelitasoitustaulukosta.`,
    );
    this.name = 'PlayingHandicapLookupError';
  }
}

