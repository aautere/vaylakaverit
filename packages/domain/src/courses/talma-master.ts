export function isTeeLabel(value: string): value is TeeLabel {
  return teeLabels.includes(value as TeeLabel);
}

export function isRatingTable(value: string): value is RatingTable {
  return value === 'men' || value === 'women';
}

export function lookupTalmaMasterPlayingHandicap(
  teeLabel: TeeLabel,
  ratingTable: RatingTable,
  handicapIndex: number,
): number {
  if (!Number.isFinite(handicapIndex)) {
    throw new PlayingHandicapLookupError(teeLabel, ratingTable, handicapIndex);
  }

  const range = talmaMasterPlayingHandicapLookupTable[teeLabel][ratingTable].find(
    ({ minimum, maximum }) => handicapIndex >= minimum && handicapIndex <= maximum,
  );

  if (!range) {
    throw new PlayingHandicapLookupError(teeLabel, ratingTable, handicapIndex);
  }

  return range.playingHandicap;
}
